def create_sample_dataset():
    """Create a simple news dataset"""
    news_data = [
        {"text": "The Federal Reserve raised interest rates by 0.25% to control inflation. The decision was unanimous.", "label": "authentic"},
        {"text": "NASA discovered evidence of water on Mars. The findings were published in Nature journal.", "label": "authentic"},
        {"text": "SHOCKING: Drink bleach to cure COVID-19! Miracle cure that doctors hate!", "label": "fake"},
        {"text": "BREAKING: Aliens exist! Government documents prove extraterrestrial contact for 50 years!", "label": "fake"},
        {"text": "United Nations announces climate summit to address global warming concerns.", "label": "authentic"},
        {"text": "Miracle pill melts 30 pounds in 1 week! No exercise needed!", "label": "fake"},
    ]

    dataset = Dataset.from_list(news_data)

    def format_instruction(example):
        instruction = f"Is this news authentic or fake? Article: {example['text']}"
        output = "authentic" if example['label'] == 'authentic' else "fake"
        return {'input_text': instruction, 'output_text': output}

    formatted = dataset.map(format_instruction)
    splits = formatted.train_test_split(test_size=0.2, seed=42)
    return DatasetDict({'train': splits['train'], 'validation': splits['test']})

