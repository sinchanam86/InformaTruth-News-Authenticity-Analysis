def simple_tokenize(examples):
    """Simplest tokenization for T5 - no as_target_tokenizer needed"""

    # Tokenize inputs
    model_inputs = tokenizer(
        examples['input_text'],
        truncation=True,
        padding='max_length',
        max_length=256
    )

    # Tokenize targets (T5 uses the same tokenizer for inputs and outputs)
    labels = tokenizer(
        examples['output_text'],
        truncation=True,
        padding='max_length',
        max_length=16
    )

    model_inputs['labels'] = labels['input_ids']
    return model_inputs

